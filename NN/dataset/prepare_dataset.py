def generate_smart_goal(category: str, goal: str, timeline: str) -> str:
    templates = [
        f"Достичь цели «{goal}» за {timeline}, выполняя конкретные шаги каждую неделю",
        f"За {timeline}: {goal} — с измеримым прогрессом каждые 2 недели",
        f"{goal.capitalize()} в течение {timeline}, отслеживая результаты еженедельно",
    ]
    return random.choice(templates)


def generate_goal_setting_dialogue() -> dict:
    category = random.choice(list(GOALS.keys()))
    goal_data = GOALS[category]
    goal = random.choice(goal_data["goals"])
    obstacle = random.choice(goal_data["obstacles"])
    timeline = random.choice(goal_data["timelines"])
    time_avail = random.choice(TIME_OPTIONS)
    reason = random.choice(REASONS)

    user_opening_templates = [
        f"Хочу {goal}.",
        f"Я давно хочу {goal}, но никак не начну.",
        f"Мне нужна помощь — хочу {goal}.",
        f"Думаю о том, чтобы {goal}. С чего начать?",
        f"Помоги мне {goal}. Не знаю, как подступиться.",
    ]

    user_detail = random.choice(USER_DETAIL_TEMPLATES).format(
        reason=reason, obstacle=obstacle, time=time_avail, goal=goal
    )

    smart_goal = generate_smart_goal(category, goal, timeline)
    steps = STEPS_POOL[category]
    step1 = random.choice(steps["step1"])
    step2 = random.choice(steps["step2"])
    step3 = random.choice(steps["step3"])
    rule = random.choice(RULES)

    plan_response = random.choice(PLAN_TEMPLATES).format(
        smart_goal=smart_goal,
        timeline=timeline,
        step1=step1,
        step2=step2,
        step3=step3,
        rule=rule,
    )

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": random.choice(user_opening_templates)},
        {"role": "assistant", "content": random.choice(CLARIFYING_TEMPLATES).format(goal=goal)},
        {"role": "user", "content": user_detail},
        {"role": "assistant", "content": plan_response},
    ]

    return {"messages": messages}


def generate_progress_dialogue() -> dict:
    is_good = random.random() > 0.4  # 60% positive progress

    if is_good:
        progress_action = random.choice(PROGRESS_ACTIONS_GOOD)
        progress_detail = random.choice(PROGRESS_DETAILS)
        user_msg = random.choice(PROGRESS_USER_TEMPLATES).format(
            progress_action=progress_action, progress_detail=progress_detail
        ).strip()

        response = random.choice(PROGRESS_GOOD_RESPONSES).format(
            praise=random.choice(PRAISES),
            next_step_1=random.choice(NEXT_STEPS),
            next_step_2=random.choice(NEXT_STEPS),
        )
    else:
        progress_action = random.choice(PROGRESS_ACTIONS_STRUGGLE)
        progress_detail = random.choice(PROGRESS_DETAILS)
        user_msg = random.choice(PROGRESS_USER_TEMPLATES).format(
            progress_action=progress_action, progress_detail=progress_detail
        ).strip()

        response = random.choice(PROGRESS_STRUGGLE_RESPONSES).format(
            empathy=random.choice(EMPATHIES),
            adjustment_1=random.choice(ADJUSTMENTS),
            adjustment_2=random.choice(ADJUSTMENTS),
        )

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_msg},
        {"role": "assistant", "content": response},
    ]

    return {"messages": messages}


def main():
    random.seed(42)

    # Load hand-crafted data
    script_dir = os.path.dirname(os.path.abspath(__file__))
    hand_crafted_path = os.path.join(script_dir, "coaching_data.json")

    with open(hand_crafted_path, "r", encoding="utf-8") as f:
        hand_crafted = json.load(f)

    print(f"Loaded {len(hand_crafted)} hand-crafted dialogues")

    # Generate synthetic data
    generated = []

    # Goal-setting dialogues (70%)
    for _ in range(700):
        generated.append(generate_goal_setting_dialogue())

    # Progress check-in dialogues (30%)
    for _ in range(300):
        generated.append(generate_progress_dialogue())

    print(f"Generated {len(generated)} synthetic dialogues")

    # Merge and shuffle
    all_data = hand_crafted + generated
    random.shuffle(all_data)

    print(f"Total: {len(all_data)} dialogues")

    # Save
    output_path = os.path.join(script_dir, "coaching_generated.json")
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(all_data, f, ensure_ascii=False, indent=2)

    print(f"Saved to {output_path}")


if __name__ == "__main__":
    main()
